#!/bin/bash
# Embeds stdlib/prelude/{core.ki,map.tpl} into compiler/src/prelude_data.ki so that kitec
# carries the prelude with it (Kite has no include_str!). Run again whenever the prelude changes.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/compiler/src/prelude_data.ki"

emit() { # emit <function name> <file>
  echo "make $1() -> string:"
  echo "    s = \"\""
  sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' "$2" | while IFS= read -r line || [ -n "$line" ]; do
    printf '    s = s + "%s\\n"\n' "$line"
  done
  echo "    return s"
  echo
}

{
  echo "// GENERATED by scripts/gen-prelude.sh from stdlib/prelude/ -- do not edit by hand."
  echo
  emit prelude_core "$ROOT/stdlib/prelude/core.ki"
  emit prelude_map_tpl "$ROOT/stdlib/prelude/map.tpl"
} > "$OUT"
echo "wrote $OUT"
